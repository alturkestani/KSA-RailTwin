def scenario_candidates(root: Path = REPO_ROOT) -> list[tuple[str, str]]:
    out = []
    for s in ("S2", "S3", "S4", "S5"):
        sc = yaml.safe_load((root / "scenarios" / f"{s}.yaml").read_text(encoding="utf-8"))
        out += [(s, c) for c in sc.get("candidates", [])]
    return out


def jubail_two(root: Path = REPO_ROOT) -> Path:
    """H8: one corridor YAML with both Jubail stations planned on the GCC section (same host
    segment as the two single-station additions), so both are inserted in one run."""
    a = yaml.safe_load(
        (root / "cities/ksa/corridors/station_addition" / f"{JUBAIL[0]}.yaml").read_text()
    )
    b = yaml.safe_load(
        (root / "cities/ksa/corridors/station_addition" / f"{JUBAIL[1]}.yaml").read_text()
    )
    new_b = [s for s in b["stations"] if s.get("class") == "planned"]
    st = sorted(a["stations"] + new_b, key=lambda s: float(s["km_post"]))
    c = {
        **a,
        "id": JUBAIL_TWO,
        "name_en": "Two new stations, Al Jubayl and Jubail Industrial City, on gcc-railway-ksa "
        "(hypothetical, CP5 H8)",
        "name_ar": "محطتان جديدتان: الجبيل ومدينة الجبيل الصناعية (افتراضي)",
        "stations": st,
        "source": f"economics.cli cases: stations of {JUBAIL[0]} and {JUBAIL[1]} (CP5 decision H8)",
        "generated_from": "CP5 H8 variant of two S5 station additions",
    }
    p = root / CASES / "variants" / f"{JUBAIL_TWO}.yaml"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(
        "# Hypothetical layer; R5 variant for CP5 decision H8 (economics.cli cases).\n"
        "# Label: synthetic demand, uncalibrated: scenario comparison, not a forecast.\n"
        + yaml.safe_dump(c, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    return p.relative_to(root)


def cost_refs(runs: list[str]) -> dict[str, str]:
    return {
        "capex_ref": ",".join(f"{r}/rcf/distribution.parquet" for r in runs),
        "opex_ref": ",".join(f"{r}/distribution.parquet" for r in runs),
        "renewals_ref": ",".join(f"{r}/distribution.parquet" for r in runs),
        "schedule_ref": ",".join(f"{r}/rcf/distribution.parquet" for r in runs),
    }


def write_case(d: dict[str, Any], root: Path) -> Path:
    d.setdefault("costs", cost_refs(str(d["cost_run"]).split(",")))
    p = root / CASES / f"{d['id']}.yaml"
    p.parent.mkdir(parents=True, exist_ok=True)
    rel = p.relative_to(root)
    p.write_text(
        HEADER.format(path=rel) + yaml.safe_dump(d, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    return rel


@app.command("cases")
def cases_cmd(root: Path = typer.Option(REPO_ROOT, hidden=True)) -> None:
    """One case per S2-S5 candidate, the S1-vs-S0 committed-programme check and the H8 variant."""
    from common.schemas import CbaCase

    (root / CASES).mkdir(parents=True, exist_ok=True)
    for old in (root / CASES).glob("CBA-*.yaml"):
        old.unlink()
    written = []
    for s, path in scenario_candidates(root):
        cid = Path(path).stem
        skip = root / "runs/costs" / cid / "SKIPPED.json"
        d = base_case(cid, s, "S1")
        d |= {
            "family": FAMILY_OF[s],
            "candidate": path,
            "cost_run": f"runs/costs/{cid}",
            "cost_spec": f"runs/network-eval/costing/{cid}.yaml",
            "cost_costing": f"runs/network-eval/costing/{cid}.costing.yaml",
        }
        if skip.exists():
            d["benefits"]["note"] = {"not_costed": json.loads(skip.read_text())["reason"]}
        d["costs"] = cost_refs([d["cost_run"]])
        CbaCase.model_validate(d)
        written.append(write_case(d, root))
    two = jubail_two(root)
    d = base_case(JUBAIL_TWO, "S5", "S1")
    d |= {
        "family": "station_addition",
        "candidate": str(two),
        "cost_run": f"runs/costs/{JUBAIL[0]}",
        "cost_spec": f"runs/network-eval/costing/{JUBAIL[0]}.yaml",
        "cost_costing": f"runs/network-eval/costing/{JUBAIL[0]}.costing.yaml",
    }
    d["costs"] = cost_refs([d["cost_run"]])
    CbaCase.model_validate(d)
    written.append(write_case(d, root))
    d = base_case("S1-committed-programme", "S1", "S0")
    d |= {
        "family": "committed_programme",
        "candidate": None,
        "cost_run": ",".join(f"runs/costs/S1-{ln}" for ln in S1_LINES),
        "cost_spec": ",".join(f"cities/ksa/lines/{ln}.yaml" for ln in S1_LINES),
        "cost_costing": None,
    }
    d["costs"] = cost_refs(d["cost_run"].split(","))
    CbaCase.model_validate(d)
    written.append(write_case(d, root))
    typer.echo(f"{len(written)} cases under {CASES} ({LABEL})")


def load_cases(root: Path = REPO_ROOT) -> list[dict[str, Any]]:
    out = []
    for p in sorted((root / CASES).glob("CBA-*.yaml")):
        d = yaml.safe_load(p.read_text(encoding="utf-8"))
        d["_path"] = str(p.relative_to(root))
        out.append(d)
    return out


def demand_cases(root: Path = REPO_ROOT) -> list[dict[str, Any]]:
    """What demandruns needs per case: id, baseline line set, scenario line set, candidate."""
    out = []
    for d in load_cases(root):
        out.append(
            {
                "id": d["id"],
                "baseline": d["baseline"],
                "scenario_lines": "S1" if d.get("candidate") else d["scenario"],
                "candidate_yaml": d.get("candidate"),
            }
        )
    return out


@app.command("inputs")
def inputs_cmd(
    workers: int = typer.Option(4),
    seed: int = seed_option(),
    root: Path = typer.Option(REPO_ROOT, hidden=True),
) -> None:
    """Matched demand runs per (population, year) group, reduced to benefit inputs."""
    from economics import demandruns

    cases = demand_cases(root)
    done = demandruns.run_all(cases, root, demandruns.INPUTS, workers)
    write_meta(
        root / demandruns.INPUTS,
        seed,
        {"cases": [c["id"] for c in cases], "calibration": str(demandruns.CALIBRATION)},
        extra={"label": LABEL, "groups": sorted(done)},
    )
    typer.echo(f"{len(done)} groups x {len(cases)} cases ({LABEL})")


def _run_one(args: tuple[str, int, str]) -> tuple[str, str]:
    path, seed, root = args
    from economics import cba

    cid = Path(path).stem
    try:
        cba.run_case(Path(path), seed, Path(root) / "runs/cba" / cid, Path(root))
        return cid, "ok"
    except Exception as e:  # noqa: BLE001 - reported per case, never silently dropped
        return cid, f"FAILED: {type(e).__name__}: {e}"


@app.command("run-all")
def run_all_cmd(
    workers: int = typer.Option(4),
    seed: int = seed_option(),
    only: str = typer.Option("", help="comma-separated case ids"),
    root: Path = typer.Option(REPO_ROOT, hidden=True),
) -> None:
    """economics.cba run for every case (parallel processes)."""
    cases = [d for d in load_cases(root) if not d.get("benefits", {}).get("note")]
    if only:
        keep = set(only.split(","))
        cases = [d for d in cases if d["id"] in keep]
    jobs = [(d["_path"], seed, str(root)) for d in cases]
    if workers <= 1:
        res = [_run_one(j) for j in jobs]
    else:
        import multiprocessing as mp

        with mp.get_context("spawn").Pool(workers) as pool:
            res = list(pool.imap_unordered(_run_one, jobs))
    for cid, st in sorted(res):
        typer.echo(f"{cid}: {st}")
    (root / "runs/cba").mkdir(parents=True, exist_ok=True)
    (root / "runs/cba/run_all.json").write_text(json.dumps(dict(res), indent=1) + "\n")


@app.command("summary")
def summary_cmd(
    seed: int = seed_option(),
    root: Path = typer.Option(REPO_ROOT, hidden=True),
) -> None:
    """runs/cba/summary.parquet: one row per case x population x horizon x rate case."""
    from economics import report

    df = report.build_summary(root)
    out = root / "runs/cba/summary.parquet"
    df.to_parquet(out, index=False)
    write_meta(out.parent / "summary-meta", seed, {"rows": len(df)}, extra={"label": LABEL})
    typer.echo(f"{len(df)} rows, {df.case.nunique()} cases -> {out.relative_to(root)}")


