def _md(df: pd.DataFrame) -> list[str]:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        cells = []
        for v in r:
            if isinstance(v, float) and pd.notna(v) and float(v).is_integer() and abs(v) > 999:
                v = f"{int(v):,}"
            elif isinstance(v, int) and abs(v) > 999:
                v = f"{v:,}"
            cells.append(str("" if v is None or (isinstance(v, float) and pd.isna(v)) else v)
                         .replace("|", "\\|"))  # fmt: skip
        out.append("| " + " | ".join(cells) + " |")
    return out


def _j(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


