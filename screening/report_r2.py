def candidates_doc(R: Path) -> str:
    reg = pd.read_parquet("cities/ksa/candidates.parquet")
    cor = pd.read_csv(R / "corridors" / "corridors.csv")
    dec = pd.read_csv(R / "corridors" / "decisions.csv")
    meta = _j(R / "merge" / "meta.json")
    rp = meta.get("result", meta).get("report", {}).get("rows_per_region", {})
    dz = R / "control_total" / "dropped_zero_grid.csv"
    n_zero = len(pd.read_csv(dz)) if dz.exists() else 0
    L = [
        f"> **Document version:** docs/candidates.md v1.1 | {DATE} | Author: screening-analyst "
        "(R2); INTEGRATE_R2 (CP3 4a/5a) | Status: draft",
        "",
        "# Candidate register `cities/ksa/candidates.parquet` (R2)",
        "",
        f"Label: **{LABEL}**. {len(reg)} rows: the 13 region registers merged "
        f"({sum(rp.values()) if rp else 1678} rows, 0 duplicates), minus {n_zero} grid rows with "
        "a raw population of 0 (CP3 5a; they stay in `cities/ksa/zones/settlements.parquet`), "
        f"plus {int(reg.notes.fillna('').str.contains('created at the R2 merge').sum())} rows "
        "created for primary GASTAT cities (`docs/screening.md` §2). Built by "
        "`./screening/run_r2.sh 1`.",
        "",
        "## 1. Fields",
        "",
        "All `RegionRow` fields (`common/schemas.py`; `region-sweep` skill) plus: `row_key` "
        "(region:osm_type:osm_id, or region:name:<name>@lat,lon), `funnel_stage` (`all` in the "
        "register; the funnel writes `long`/`served` in `runs/r2/long-list`), `primary_city` and "
        "`primary_match_tier` (A-r2-001), `primary_unclaimed`, `pop_grid_raw`, "
        "`grid_scale_factor`, `grid_scaled` (A-screen-040).",
        "",
        "## 2. Counts",
        "",
    ]
    c = (
        reg.groupby("region")
        .agg(
            rows=("row_key", "size"),
            official=("pop_type", lambda q: int((q == "official").sum())),
            derived=("pop_type", lambda q: int((q == "derived").sum())),
            grid=("pop_type", lambda q: int((q == "grid").sum())),
            no_population=("pop_type", lambda q: int(q.isna().sum())),
            ge_5k=("tag_5k", lambda q: int(q.astype(bool).sum())),
            centres=("is_governorate_centre", lambda q: int(q.astype(bool).sum())),
            roles=("economic_roles", lambda q: int(sum(len(x) > 0 for x in q))),
        )
        .reset_index()
    )
    L += _md(c) + [""]
    L += [
        "## 3. Sources",
        "",
        "Populations: GASTAT Census 2022 primary TA1 exports (S-cp2-gastat-007/008, "
        "`official`/`verified`), relays where no primary row exists (`secondary`), OSM tags "
        "(`derived`), WorldPop 2020 gap-fill (`grid`, `unverified`, S-r1a-505/506); per-row "
        "`sources` and region notes `docs/regions/<region>.md`. OSM © OpenStreetMap "
        "contributors, ODbL 1.0.",
        "",
        "## 4. Corridor families (hypothetical layer; generated, uncosted)",
        "",
        "Generated by `uv run python -m screening.corridors generate --seed 1` from the short list "
        "and `cities/ksa/assumptions/corridor_rules.yaml` (A-corr-001…015); one YAML per "
        "corridor under `cities/ksa/corridors/<family>/`, listed in `scenarios/S2…S5.yaml` "
        "(baseline S1). Alignments are indicative great-circle sketches, not engineering "
        "alignments; terrain and structure shares are proxies (A-corr-013/014). No corridor "
        "appears in S0 or S1.",
        "",
    ]
    fam = cor.groupby("family").size().to_dict()
    L += ["Counts: " + ", ".join(f"{k} {v}" for k, v in fam.items()) + ".", ""]
    L += _md(cor[["family", "id", "rule", "line_type", "length_km", "stations", "tunnel",
                  "viaduct"]])  # fmt: skip
    L += ["", "### Dominated, merged or redirected candidates", ""] + _md(dec) + [""]
    return "\n".join(L) + "\n"


@app.command()
def main(
    run: Path = typer.Option(Path("runs/r2"), "--run"),
    weights: Path = typer.Option(Path("cities/ksa/assumptions/screening_weights.yaml")),
) -> None:
    Path("docs/screening.md").write_text(screening_doc(run, weights), encoding="utf-8")
    Path("docs/candidates.md").write_text(candidates_doc(run), encoding="utf-8")
    typer.echo("wrote docs/screening.md, docs/candidates.md")


if __name__ == "__main__":
    app()
