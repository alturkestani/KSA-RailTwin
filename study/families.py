"""All-families comparison layout (STUDY_RJ_FAMILIES item 1): S1 plus every S2-S5 corridor of the
R6_V3 library. A COMPARISON LAYOUT, NOT THE RECOMMENDED PROGRAMME, and not an S6 search result:
connectivity is neither a constraint nor an objective, and nothing here runs the judge or writes
into runs/r6/top5/, the dashboard SWITCHER, R7 or the R8 deliverables.

  uv run python -m study.families layout       # scenarios/study/all-families.yaml
  uv run python -m study.families inventory    # runs/study/families/inventory.{csv,json}
  uv run python -m study.families map          # docs/study-rj/all-families-map.png

Label: synthetic demand, uncalibrated: scenario comparison, not a forecast.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd
import typer
import yaml

from common import REPO_ROOT
from common.labels import ALIGNMENT_LIMITATION, LABEL
from common.runmeta import write_meta

LIBRARY = Path("runs/r6/v3/library/library.json")
CORRIDORS = Path("cities/ksa/corridors")
ALIGNMENTS = Path("cities/ksa/alignments")
SCENARIO = Path("scenarios/study/all-families.yaml")
OUT = Path("runs/study/families")
MAP = Path("docs/study-rj/all-families-map.png")
FAMILY_DIRS = {
    "S2": "trunk_gap",
    "S3": "branch_spur",
    "S4": "commuter_belt",
    "S5": "station_addition",
}
# the 73rd library id is a CBA variant that combines two S5 station additions already listed
# (optimise/layout.py corridor_path); adding it too would draw the same two stations twice
COMBINED = {
    "S5-station_addition-jubail-two-stations": [
        "S5-station_addition-al-jubayl",
        "S5-station_addition-al-jubayl-royal-commission",
    ]
}
TITLE = "S1 + all S2-S5 library corridors (all-families comparison layout, not the recommended programme)"
KIND_LABEL = "comparison layout, not the recommended programme"

app = typer.Typer(add_completion=False, help=__doc__, no_args_is_help=True)


def library_ids(root: Path = REPO_ROOT) -> list[str]:
    return list(json.loads((root / LIBRARY).read_text(encoding="utf-8"))["ids"])


def members(root: Path = REPO_ROOT) -> list[str]:
    """Library base ids drawn in the layout: every id with its own corridor file (72 of 73)."""
    return [i for i in library_ids(root) if i not in COMBINED]


def corridor_file(cid: str) -> Path:
    return CORRIDORS / FAMILY_DIRS[cid.split("-")[0]] / f"{cid}.yaml"


def scenario(root: Path = REPO_ROOT) -> dict[str, Any]:
    s1 = yaml.safe_load((root / "scenarios/S1.yaml").read_text(encoding="utf-8"))
    ids = members(root)
    return {
        "id": "S1-S5-all-families",
        "kind": "comparison_layout",
        "label": KIND_LABEL,
        "title": TITLE,
        "layer": "hypothetical (ours)",
        "layers": ["existing", "committed", "hypothetical"],
        "baseline": "S1",
        "lines": {"include": list(s1["lines"]["include"])},
        "candidates": [str(corridor_file(i)) for i in ids],
        "library": {
            "source": str(LIBRARY),
            "ids_in_library": len(library_ids(root)),
            "ids_drawn": len(ids),
            "not_drawn": {k: f"combines {' + '.join(v)}, both drawn" for k, v in COMBINED.items()},
        },
        "notes": [
            "Not an S6 search result and not scored: the judge was not run on this layout.",
            "Connectivity is neither a constraint nor an objective (Tariq, 6 Nov 2026).",
            "S1 is included as it stands, with the committed Landbridge geometry unchanged.",
            "Overlapping alternatives are all drawn (e.g. S2-trunk_gap-riyadh-jeddah beside the "
            "committed Landbridge); route-km is a sum of corridors, not a network length.",
            "The Riyadh-Jeddah study routes (scenarios/study/rj-*.yaml) are not in this layout.",
        ],
        "population_scenario": s1.get("population_scenario"),
        "seed": 1,
        "labels": [LABEL],
        "source": "prompts/STUDY_RJ_FAMILIES.md item 1 (Tariq, 6 Nov 2026); R6_V3 library ids",
    }


@app.command("layout")
def layout_cmd(root: Path = typer.Option(REPO_ROOT, hidden=True)) -> None:
    """Write the all-families comparison layout."""
    d = scenario(root)
    head = (
        "# Version: all-families.yaml v1.0 | 6 Nov 2026 | Author: STUDY_RJ_FAMILIES | Status: draft\n"
        f"# {TITLE}.\n# Generated by `study.families layout`; do not edit by hand. Label: {LABEL}.\n"
    )
    p = root / SCENARIO
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(head + yaml.safe_dump(d, sort_keys=False, allow_unicode=True), encoding="utf-8")
    typer.echo(f"{SCENARIO}: {len(d['candidates'])} corridors")


def inventory(root: Path = REPO_ROOT) -> pd.DataFrame:
    rows = []
    for cid in members(root):
        c = yaml.safe_load((root / corridor_file(cid)).read_text(encoding="utf-8"))
        fam = c["family"]
        side = root / ALIGNMENTS / f"{cid}.json"
        routed_km = json.loads(side.read_text())["length_km"] if side.exists() else None
        new_km = (
            0.0
            if fam == "station_addition"
            else float(routed_km if routed_km is not None else c["length_km"])
        )
        rows.append(
            {
                "id": cid,
                "scenario": cid.split("-")[0],
                "family": fam,
                "line_type": c["line_type"],
                "new_route_km": round(new_km, 3),
                "km_basis": "station on an existing/committed line (no new route-km)"
                if fam == "station_addition"
                else (
                    "routed alignment (frozen v1)"
                    if routed_km is not None
                    else "corridor length_km"
                ),
                "new_stations": sum(1 for s in c["stations"] if s.get("class") == "planned")
                if fam == "station_addition"
                else len(c["stations"]),
            }
        )
    return pd.DataFrame(rows)


@app.command("inventory")
def inventory_cmd(root: Path = typer.Option(REPO_ROOT, hidden=True)) -> None:
    """Count, route-km and families of the layout."""
    df = inventory(root)
    out = root / OUT
    out.mkdir(parents=True, exist_ok=True)
    df.to_csv(out / "inventory.csv", index=False)
    by = (
        df.groupby(["scenario", "family"])
        .agg(corridors=("id", "count"), new_route_km=("new_route_km", "sum"))
        .reset_index()
    )
    summ = {
        "label": LABEL,
        "kind": KIND_LABEL,
        "corridors": int(len(df)),
        "library_ids": len(library_ids(root)),
        "new_route_km_sum": round(float(df.new_route_km.sum()), 1),
        "note": "sum over corridors; overlapping alternatives counted once each; not a network length",
        "by_family": by.round(1).to_dict("records"),
        "km_basis_counts": df.km_basis.value_counts().to_dict(),
    }
    (out / "inventory.json").write_text(json.dumps(summ, indent=1) + "\n", encoding="utf-8")
    write_meta(out, 1, {"scenario": scenario(root)}, extra={"label": LABEL})
    typer.echo(json.dumps(summ, indent=1))


@app.command("map")
def map_cmd(root: Path = typer.Option(REPO_ROOT, hidden=True)) -> None:
    """S1 layers plus every library corridor, coloured by family; OSM credit; both labels."""
    import geopandas as gpd
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    from common import figures as cf

    cols = {"S2": "#e07b00", "S3": "#1f77b4", "S4": "#2ca02c", "S5": "#8e44ad"}
    names = {
        "S2": "S2 trunk gaps",
        "S3": "S3 branches/spurs",
        "S4": "S4 commuter belts",
        "S5": "S5 station additions",
    }
    df = inventory(root)
    cf.register_fonts()
    fig, ax = plt.subplots(figsize=(10, 9.6), dpi=110)
    handles = cf._base_layers(ax)
    for r in df.itertuples():
        if r.scenario == "S5":
            c = yaml.safe_load((root / corridor_file(r.id)).read_text(encoding="utf-8"))
            for s in c["stations"]:
                if s.get("class") == "planned":
                    ax.scatter(
                        s["lon"],
                        s["lat"],
                        marker="*",
                        s=110,
                        color=cols["S5"],
                        edgecolor="white",
                        lw=0.4,
                        zorder=8,
                    )
            continue
        p = root / ALIGNMENTS / f"{r.id}.geojson"
        g = gpd.read_file(p)
        if "kind" in g.columns:
            g = g[g["kind"] == "routed"]
        g.plot(ax=ax, color=cols[r.scenario], lw=1.6, alpha=0.85, zorder=5)
    for k in ("S2", "S3", "S4"):
        n = int((df.scenario == k).sum())
        km = df[df.scenario == k].new_route_km.sum()
        handles.append(
            Line2D(
                [],
                [],
                color=cols[k],
                lw=1.8,
                label=f"hypothetical (ours): {names[k]} ({n}; {km:,.0f} route-km)",
            )
        )
    n5 = int((df.scenario == "S5").sum())
    handles.append(
        Line2D(
            [],
            [],
            color=cols["S5"],
            marker="*",
            ls="",
            markersize=9,
            label=f"hypothetical (ours): {names['S5']} ({n5})",
        )
    )
    cf._aspect(ax, 24.0)
    ax.set_axis_off()
    cf._osm(ax)
    ax.legend(
        handles=handles,
        loc="lower left",
        fontsize=7,
        title="rail layers (never mixed)",
        title_fontsize=7.5,
        framealpha=0.9,
    )
    ax.set_title(
        "S1 + all S2-S5 library corridors: comparison layout, not the recommended programme",
        fontsize=10,
    )
    fig.text(
        0.01,
        0.01,
        f"{LABEL}. {len(df)} library corridors ({df.new_route_km.sum():,.0f} route-km summed over corridors, "
        "overlaps counted each time; not a network length). Not an S6 search result; not scored.\n"
        f"Alignment limitation: {ALIGNMENT_LIMITATION}.",
        fontsize=6.3,
        va="bottom",
        wrap=True,
    )
    dest = root / MAP
    dest.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(dest, dpi=110, metadata={"Software": None})
    plt.close(fig)
    typer.echo(f"{dest} {dest.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    app()
