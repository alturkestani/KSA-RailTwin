"""Generated tables for docs/alignments-tables.md (R4_ALIGN) from the run outputs; never typed by hand.

Reads runs/align/validation-s1, runs/align/tune-s1 and tune3-s1, cities/ksa/alignments (sidecars),
runs/r4a/compare-s1 and the frozen weights hash. Writes docs/alignments-tables.md.
  uv run python scripts/r4a_doc_tables.py [--seed 1]
Label: synthetic demand, uncalibrated: scenario comparison, not a forecast.
"""

from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from network import align  # noqa: E402

SEED = int(sys.argv[sys.argv.index("--seed") + 1]) if "--seed" in sys.argv else 1


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append(
            "| "
            + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in r)
            + " |"
        )
    return "\n".join(out)


def fmt(x: float, n: int = 1) -> str:
    return "" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:,.{n}f}"


def main() -> None:
    w = align.load_weights()
    h = align.weights_hash(w)
    val = pd.read_csv(ROOT / f"runs/align/validation-s{SEED}/validation.csv")
    t = pd.DataFrame(
        {
            "line": val.line,
            "class (cap)": [f"{c} ({'2.5' if c == 'hsr' else '1.25'} %)" for c in val["class"]],
            "routed km": val.routed_km.map(fmt),
            "reference km (station span along OSM)": val.ref_km_station_span.map(fmt),
            "length error": (val.length_error * 100).map(lambda x: f"{x:+.1f} %"),
            "length within ±5 %": val.length_ok.map({True: "Y", False: "N"}),
            "mean offset km": val.mean_offset_km.map(lambda x: fmt(x, 2)),
            "offset < 2 km": val.offset_ok.map({True: "Y", False: "N"}),
            "Hausdorff km": val.hausdorff_km.map(lambda x: fmt(x, 1)),
            "P90 offset km": val.p90_offset_km.map(lambda x: fmt(x, 1)),
            "tunnel km (share), routed": [
                f"{fmt(a)} ({b * 100:.2f} %)"
                for a, b in zip(val.tunnel_km, val.tunnel_share, strict=True)
            ],
            "tunnel km (share), OSM tags": [
                f"{fmt(a)} ({b * 100:.2f} %)"
                for a, b in zip(val.osm_tunnel_km, val.osm_tunnel_share, strict=True)
            ],
            "viaduct km (share), routed": [
                f"{fmt(a)} ({b * 100:.2f} %)"
                for a, b in zip(val.viaduct_km, val.viaduct_share, strict=True)
            ],
            "bridge km (share), OSM tags": [
                f"{fmt(a)} ({b * 100:.2f} %)"
                for a, b in zip(val.osm_bridge_km, val.osm_bridge_share, strict=True)
            ],
        }
    )
    parts = [
        "> **Document version:** docs/alignments-tables.md v1.1 | "
        + dt.date(2026, 11, 1).strftime("%-d %b %Y")
        + " | Author: generated by scripts/r4a_doc_tables.py (R4_ALIGN) | Status: draft",
        "",
        "# Terrain-aware alignments: generated tables (R4_ALIGN)",
        "",
        "Generated from the run outputs; do not edit by hand. **Label: synthetic demand, uncalibrated: scenario comparison, not a forecast.** Alignments are hypothetical (ours): indicative engineering sketches, not designs.",
        "",
        f"Frozen weights: `cities/ksa/assumptions/align_weights.yaml`, hash `{h}` (`align_weights.sha256`; recorded in every corridor run's `meta.json`).",
        "",
        f"## 1. Validation (runs/align/validation-s{SEED}/validation.csv)",
        "",
        md(t),
        "",
        "Reference length = the line YAML's station km-post span (cumulative path along the OSM track, rail-data-scout method). Offsets = mean of the two directed mean distances (routed→OSM, OSM→routed) over 2,000 points each, against the OSM line clipped between the end stations. OSM structure km = OSM rail ways tagged bridge/tunnel within 50 m of the line (`data/ksa/osm/ksa-rail.osm.pbf`).",
        "",
    ]
    tune = pd.read_csv(ROOT / f"runs/align/tune-s{SEED}/tune.csv")
    tt = tune[["pass", "sweep", "param", "value", "objective"]].copy()
    tt["objective"] = tt.objective.map(lambda x: fmt(x, 3))
    parts += [
        f"## 2. Tuning log (runs/align/tune-s{SEED}; objective A-align-070, km)",
        "",
        md(tt),
        "",
    ]
    sc = pd.read_csv(ROOT / "cities/ksa/alignments/summary.csv")
    sc["family"] = sc.id.str.split("-").str[1]
    d = sc.detour_ratio
    q = np.percentile(d, [0, 10, 50, 90, 100])
    fam = (
        sc.groupby("family")
        .agg(
            corridors=("id", "count"),
            routed_km=("length_km", "sum"),
            straight_km=("straight_km_legs", "sum"),
            tunnel_km=("tunnel_km", "sum"),
            viaduct_km=("viaduct_km", "sum"),
            earthworks_km=("earthworks_km", "sum"),
            restricted_km=("restricted_km", "sum"),
        )
        .reset_index()
    )
    tot = fam.sum(numeric_only=True)
    fam.loc[len(fam)] = [
        "all",
        int(tot.corridors),
        tot.routed_km,
        tot.straight_km,
        tot.tunnel_km,
        tot.viaduct_km,
        tot.earthworks_km,
        tot.restricted_km,
    ]
    fam["detour (routed / straight)"] = (fam.routed_km / fam.straight_km).map(lambda x: f"{x:.3f}")
    for k in (
        "routed_km",
        "straight_km",
        "tunnel_km",
        "viaduct_km",
        "earthworks_km",
        "restricted_km",
    ):
        fam[k] = fam[k].map(fmt)
    parts += [
        "## 3. Routed corridors (cities/ksa/alignments/summary.csv)",
        "",
        f"Detour ratio (routed km / straight-line legs) over {len(sc)} corridors: min {q[0]:.3f}, P10 {q[1]:.3f}, P50 {q[2]:.3f}, P90 {q[3]:.3f}, max {q[4]:.3f}.",
        "",
        "Totals include the corridors flagged `profile_feasible: false` (A-align-091), whose structures rest on a profile that does not meet the cap: "
        + (
            "; ".join(
                f"{r.id} ({fmt(r.tunnel_km)} km tunnel, {fmt(r.viaduct_km)} km viaduct)"
                for r in sc[~sc.profile_feasible.astype(bool)].itertuples()
            )
            or "none"
        )
        + f". Without them: tunnel {fmt(sc[sc.profile_feasible.astype(bool)].tunnel_km.sum())} km, viaduct {fmt(sc[sc.profile_feasible.astype(bool)].viaduct_km.sum())} km.",
        "",
        md(fam),
        "",
    ]
    per = sc[
        [
            "id",
            "line_type",
            "straight_km_legs",
            "length_km",
            "detour_ratio",
            "tunnel_km",
            "viaduct_km",
            "earthworks_km",
            "restricted_km",
            "min_curve_kmh",
        ]
    ].copy()
    for k in (
        "straight_km_legs",
        "length_km",
        "tunnel_km",
        "viaduct_km",
        "earthworks_km",
        "restricted_km",
    ):
        per[k] = per[k].map(fmt)
    parts += ["### Per corridor", "", md(per), ""]
    alt = ROOT / "cities/ksa/alignments/alternatives/summary.csv"
    if alt.exists():
        a = pd.read_csv(alt)
        for k in (
            "straight_km_legs",
            "length_km",
            "tunnel_km",
            "viaduct_km",
            "earthworks_km",
            "restricted_km",
        ):
            a[k] = a[k].map(fmt)
        parts += [
            "### Trunk alternatives routed for the detour test (cities/ksa/alignments/alternatives/)",
            "",
            md(a[per.columns]),
            "",
        ]
    cmp_dir = ROOT / f"runs/r4a/compare-s{SEED}"
    if cmp_dir.exists():
        tot = json.loads((cmp_dir / "totals.json").read_text())
        c = pd.read_csv(cmp_dir / "corridors.csv")
        cc = c[
            [
                "candidate",
                "status",
                "km_before",
                "km_after",
                "run_min_p50_before",
                "run_min_p50_after",
                "capex_p50_before",
                "capex_p50_after",
                "capex_uplifted_p50_before",
                "capex_uplifted_p50_after",
                "towns_within_30_ivt_before",
                "towns_within_30_ivt_after",
                "rank_capex_before",
                "rank_capex_after",
                "rank_cost_per_reach_before",
                "rank_cost_per_reach_after",
            ]
        ].copy()
        for k in cc.columns:
            if k.startswith(("km_", "run_min")):
                cc[k] = cc[k].map(fmt)
            elif k.startswith("capex"):
                cc[k] = (cc[k] / 1e3).map(lambda x: fmt(x, 2))
        fam_tot = (
            c.assign(family=c.candidate.str.split("-").str[1])
            .groupby("family")[
                [
                    "capex_p50_before",
                    "capex_p50_after",
                    "capex_uplifted_p50_before",
                    "capex_uplifted_p50_after",
                ]
            ]
            .sum()
            .div(1e3)
            .round(1)
            .reset_index()
        )
        parts += [
            f"## 4. Before (straight sketches, R4) vs after (routed) (runs/r4a/compare-s{SEED})",
            "",
            "Capex in SAR bn (2025 SAR, the cost-register index base), P50 of the base estimate and of the reference-class uplifted estimate; ranks 1 = cheapest (capex) or lowest uplifted capex per person newly reached within 60 in-vehicle minutes (corridors reaching nobody rank last). Before = R4 runs on great-circle station chains (costs at straight-line km, running time at 1.2 x straight); after = routed km, measured terrain and structures, curve speed limits.",
            "",
            f"- Corridors: {tot['corridors_before']} before, {tot['corridors_after']} after; dropped after routing: {', '.join(tot['dropped']) or 'none'}; new: {', '.join(tot['new']) or 'none'}.",
            f"- Not costed after routing (grade-infeasible at the class cap, A-align-091): {', '.join(tot.get('not_costed_after', [])) or 'none'}.",
            f"- Sum of base capex P50 (S2-S5): SAR {tot['capex_p50_sum_before_sar_bn']} bn before ({tot['corridors_before']} corridors), SAR {tot['capex_p50_sum_after_sar_bn']} bn after ({tot['corridors_after'] - len(tot.get('not_costed_after', []))} costed); a sum of medians, for scale only, not a programme cost.",
            f"- 30-minute test (candidate scenarios, town-metro pairs within 30 in-vehicle minutes): {tot['pairs_within_30_ivt_before']} before, {tot['pairs_within_30_ivt_after']} after ({tot['pairs_gained']} gained, {tot['pairs_lost']} lost).",
            f"- Corridors whose rank changes by more than 5 places: {len(tot['corridor_rank_changes_gt5'])}; towns (screening funnel): {len(tot['town_rank_changes_gt5'])}.",
            "",
            "### Capex P50 by family (SAR bn)",
            "",
            md(fam_tot),
            "",
            "### Per corridor",
            "",
            md(cc),
            "",
        ]
        big = pd.read_csv(cmp_dir / "corridor_rank_changes.csv")
        if len(big):
            b = big[
                [
                    "candidate",
                    "rank_capex_before",
                    "rank_capex_after",
                    "rank_capex_change",
                    "rank_cost_per_reach_before",
                    "rank_cost_per_reach_after",
                    "rank_cost_per_reach_change",
                ]
            ]
            parts += ["### Corridor rank changes of more than 5 places", "", md(b), ""]
        tb = pd.read_csv(cmp_dir / "town_rank_changes.csv")
        parts += [
            "### Town rank changes of more than 5 places (screening funnel, minutes criterion)",
            "",
            md(tb) if len(tb) else "None: no town changes rank (see docs/alignments.md section 6).",
            "",
        ]
        c30 = pd.read_csv(cmp_dir / "commute30.csv")
        fl = c30[c30.flip.isin(["gained", "lost"])][
            ["scenario", "metro", "town", "ivt_min_before", "ivt_min_after", "flip"]
        ]
        for k in ("ivt_min_before", "ivt_min_after"):
            fl[k] = fl[k].map(fmt)
        parts += ["### 30-minute test pairs that change", "", md(fl) if len(fl) else "None.", ""]
    (ROOT / "docs/alignments-tables.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("docs/alignments-tables.md written")


if __name__ == "__main__":
    main()
